"""
schema.py — TaskNet's database schema, in third normal form.

Stored tables (BASE_SCHEMA)
  * 1NF: no repeating groups. The lists an event proposal holds (outputs,
    participant groups, phases, schedule, budget rows, committees, indicators,
    signatories, ...) are rows of child tables with a `position`, never JSON
    in a column.
  * 2NF/3NF: every non-key column depends on the key, the whole key and
    nothing but the key. Derived values are not stored: full names,
    participant totals and a special task's weighted average are computed
    when read. A submission's sender, date and status live once, on the report.
  * Optional details (a middle name, a suffix, a venue pin, a review comment)
    are nullable columns of the table they describe: NULL means "not given".
  Tables whose shape changed have singular names (personnel, event, task,
  report, ...); tables that were already in this form keep their names.

Read views (READ_VIEWS)
  Views with the familiar names (users, events, tasks, reports, ...) give the
  shapes the application reads (e.g. full_name, an event's lists as JSON), so
  read queries are unchanged. Views are read-only: writes go to the stored
  tables (see store.py and event_store.py).
"""


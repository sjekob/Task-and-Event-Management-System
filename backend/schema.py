def _list(table: str, owner: str, ref: str, columns: str) -> str:
    """An ordered list belonging to an owner (a repeating group, normalized)."""
    return (f"CREATE TABLE IF NOT EXISTS {table} (\n    {owner} INTEGER NOT NULL REFERENCES {ref} ON DELETE CASCADE,\n"
            f"    position INTEGER NOT NULL CHECK(position >= 0),\n    {columns},\n    PRIMARY KEY({owner}, position)\n);\n")


def _in(values) -> str:
    return ",".join(f"'{x}'" for x in values)



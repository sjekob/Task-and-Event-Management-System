def _json_list(table: str, obj: str, alias: str = "x") -> str:
    """A JSON array (as text) of an owner's ordered list rows, or NULL when it has none."""
    return f"(SELECT json_agg({obj} ORDER BY {alias}.position)::text FROM {table} {alias} WHERE {alias}.event_id = e.id)"


